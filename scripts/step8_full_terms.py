def main():
    rows = [json.loads(l) for l in open(SRC, encoding="utf-8")]
    n_terms = {"单字词": 0, "双字词": 0, "三字词": 0}
    n_review = 0
    empty = []
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        for i, r in enumerate(rows, 1):
            sent = r["classical"]
            terms = extract_terms_course(sent)
            if not terms and sent in EMPTY_FIX:
                terms = []
                for term, mng, err in EMPTY_FIX[sent]:
                    if not mng:
                        continue
                    cc = len(st.CJK.findall(term))
                    tt = "单字词" if cc == 1 else ("双字词" if cc == 2 else "三字词")
                    t = {"term": term, "char_count": cc, "term_type": tt,
                         "meaning_in_this_sentence": mng,
                         "typical_error_mode": err, "needs_review": True}
                    terms.append(t)
                    n_review += 1
            for t in terms:
                n_terms[t["term_type"]] += 1
                n_review += 1 if t.get("needs_review") else 0
            if not terms:
                empty.append((i, sent))
            rec = {"id": f"c{i:03d}", "title": r.get("title", ""),
                   "source": r.get("source_work", ""),
                   "classical_sentence": sent, "terms": terms}
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    total = sum(n_terms.values())
    multi = n_terms["双字词"] + n_terms["三字词"]
    brief = [
        f"句子数: {len(rows)}  词项总数: {total}",
        f"分布: 单字 {n_terms['单字词']} / 双字 {n_terms['双字词']} / 三字 {n_terms['三字词']}",
        f"双字+三字占比: {multi / total * 100:.1f}%",
        f"needs_review: {n_review}",
        f"空 terms 句: {len(empty)} {[s for _, s in empty[:5]]}",
    ]
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    print("\n".join(brief))
    with open(OUT.replace(".jsonl", "_brief.txt"), "w", encoding="utf-8") as f:
        f.write("\n".join(brief) + "\n")


if __name__ == "__main__":
    main()
