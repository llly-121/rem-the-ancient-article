def extract_terms_course(sent):
    base = st.extract_terms(sent)
    occupied = []
    for t in base:
        for m in re.finditer(re.escape(t["term"]), sent):
            occupied.append(m.span())

    def free(s, e):
        return all(e <= a or s >= b for a, b in occupied)

    def make(term, mng, err, review=False):
        n = len(CJK.findall(term))
        d = {"term": term, "char_count": n,
             "term_type": {1: "单字词", 2: "双字词", 3: "三字词"}[n],
             "meaning_in_this_sentence": mng,
             "typical_error_mode": err}
        if review:
            d["needs_review"] = True
        return d

    extra = []
    # 1) 课文词典（先三字后双字）；歧义单字标 needs_review
    for d in (PROSE_DICT3, PROSE_DICT2):
        for term, (mng, err) in d.items():
            for m in re.finditer(re.escape(term), sent):
                s, e = m.span()
                if free(s, e):
                    occupied.append((s, e))
                    extra.append(make(term, mng, err,
                                      review=term in AMBIG_SINGLES))
    # 1b) 上下文限定的特例单字
    for pat, term, mng, err in (
        (r"乡(?=为)", "乡", "本句通『向』，从前（『乡为身死而不受』）",
         "通假字还原错误：乡通向"),
        (r"(?<=者)耳(?=[。！？；])", "耳", "本句为语气词『罢了』",
         "误解为『耳朵』"),
    ):
        for m in re.finditer(pat, sent):
            s, e = m.span()
            if free(s, e):
                occupied.append((s, e))
                extra.append(make(term, mng, err, review=True))
    # 2) 地名后缀兜底（needs_review）
    for m in PLACE_SUFFIX.finditer(sent):
        s, e = m.span()
        if free(s, e):
            occupied.append((s, e))
            extra.append(make(
                m.group(1),
                "（专名·待考）本句涉及的地名（山／水／城郭／建筑），具体所指待查",
                "漏抽专名，或误当普通词解其字面义", True))

    # 句内去重（同词只保留首次出现）
    seen = set()
    dedup = []
    for t in base + extra:
        if t["term"] in seen:
            continue
        seen.add(t["term"])
        dedup.append(t)
    return dedup


