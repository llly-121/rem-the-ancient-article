flat = json.load(open('data/flat_terms.json', encoding='utf-8'))
rows, problems = [], []
for idx in range(200):
    r = flat[idx]
    te, nr, mm, terr, sug, note = A.get(idx, (None, 1, 0, 1, None, "未标注"))
    full = r['english']
    mt = None
    if te:
        if te in full:
            mt = "substring"
        else:
            problems.append((idx, r['term'], te, full))
            mt = "MISMATCH"
    rows.append({
        "idx": idx, "sent_id": r['sent_id'], "title": r['title'],
        "term": r['term'], "term_type": r['term_type'],
        "meaning_in_this_sentence": r['meaning'],
        "classical_sentence": r['classical'],
        "full_english": full,
        "term_english": te,
        "match_type": mt,
        "needs_revision": bool(nr),
        "meaning_mismatch": bool(mm),
        "term_extraction_error": bool(terr),
        "suggested_term_english": sug or "",
        "note": note,
    })

with open('data/term_pairs_sample.jsonl', 'w', encoding='utf-8', newline='\n') as f:
    for x in rows:
        f.write(json.dumps(x, ensure_ascii=False) + '\n')

n = len(rows)
nr_n = sum(x['needs_revision'] for x in rows)
